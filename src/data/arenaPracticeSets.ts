export function shuffleWithSeed<T>(items: readonly T[], seed: number): T[] {
  const arr = [...items];
  let s = (seed ^ 0x9e3779b9) >>> 0;
  const nextRand = () => {
    s = (Math.imul(s, 1664525) + 1013904223) >>> 0;
    return s / 4294967296;
  };
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(nextRand() * (i + 1));
    const tmp = arr[i];
    arr[i] = arr[j];
    arr[j] = tmp;
  }
  return arr;
}

