export const ORIGINAL_TO_SEQUENTIAL_LECTURE_NUMBER: Record<number, number> = {
  1: 1,
  2: 2,
  7: 3,
  8: 4,
  3: 5,
  4: 6,
  9: 7,
  10: 8,
  5: 9,
  6: 10,
  11: 11,
  12: 12,
};

export function enrichSyllabusWithEnhancements(lectures: LectureUnit[]): LectureUnit[] {
  const enriched = lectures.map((lec) => {
    const origNum = lec.lectureNumber;
    const isCore = !lec.isCustomAI && origNum >= 1 && origNum <= 12;
    const sequentialNumber = isCore
      ? ORIGINAL_TO_SEQUENTIAL_LECTURE_NUMBER[origNum] ?? origNum
      : origNum;
    const sequentialLevel = isCore
      ? sequentialNumber <= 4
        ? 'B1'
        : sequentialNumber <= 8
        ? 'B2'
        : 'C1'
      : lec.level;

    const extraSeeds = EXTRA_DEEP_WORDS_BY_LECTURE[origNum] || [];
    const existingIds = new Set(lec.moduleA_vocabulary.map((v) => v.id));

    const extraVocab: VocabularyItem[] = [];
    const extraPronun: PronunciationItem[] = [];

    for (const seed of extraSeeds) {
      const vocabId = `l${origNum}-${seed.idSuffix}`;
      if (existingIds.has(vocabId)) continue;

      extraVocab.push({
        id: vocabId,
        word: seed.word,
        ipa: seed.ipa,
        partOfSpeech: seed.pos,
        segments: seed.segments,
        silentLettersSummary: seed.silentSummary,
        nepaliMeaning: seed.nepaliMeaning,
        nepaliTransliteration: seed.translit,
        englishExample: seed.exampleEn,
        nepaliExampleTranslation: seed.exampleNe,
        usageTipNepali: seed.tipNe,
      });

      const pIndex = seed.idSuffix.replace('v', 'p');
      extraPronun.push({
        id: `l${origNum}-${pIndex}`,
        wordId: vocabId,
        word: seed.word,
        ipa: seed.ipa,
        syllables: seed.syllables,
        stressedSyllableIndex: seed.stressIdx,
        simplifiedPhonetic: seed.simplifiedPhonetic,
        nepaliPhoneticHint: seed.nepaliPhonetic,
        ruleTitle: seed.ruleTitle,
        ruleExplanationNepali: seed.tipNe,
        commonMispronunciation: seed.commonMistake,
      });
    }

    const dialogue =
      LECTURE_DIALOGUES[origNum] ||
      lec.moduleE_dialogue ||
      buildFallbackDialogueForLecture(lec);
    const builders =
      LECTURE_SENTENCE_BUILDERS[origNum] ||
      lec.moduleD_grammar.sentenceBuilders ||
      [];

    return {
      ...lec,
      lectureNumber: sequentialNumber,
      level: sequentialLevel,
      moduleA_vocabulary: [...lec.moduleA_vocabulary, ...extraVocab],
      moduleB_pronunciation: [...lec.moduleB_pronunciation, ...extraPronun],
      moduleD_grammar: {
        ...lec.moduleD_grammar,
        sentenceBuilders: builders,
      },
      moduleE_dialogue: dialogue,
    };
  });

  return [...enriched].sort((a, b) => a.lectureNumber - b.lectureNumber);
}

